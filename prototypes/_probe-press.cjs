const { app, BrowserWindow } = require('electron')
const path = require('node:path')
const ROOT = path.join(__dirname, '..')
app.disableHardwareAcceleration()
const wait = (ms) => new Promise((r) => setTimeout(r, ms))
app.whenReady().then(async () => {
  const win = new BrowserWindow({ width: 1440, height: 960, show: true,
    webPreferences: { preload: path.join(ROOT, 'out', 'preload', 'index.js'), contextIsolation: true } })
  await win.loadURL('file:///' + path.join(ROOT, 'out', 'renderer', 'index.html').replace(/\\/g, '/'))
  await wait(1500)
  win.focus()
  const box = await win.webContents.executeJavaScript(`(() => { const r = document.querySelector('.input').getBoundingClientRect(); return { x: Math.round(r.x + r.width/2), y: Math.round(r.y + r.height/2) }; })()`)
  const READ = `(() => { const el = document.activeElement && document.activeElement.classList.contains('input') ? document.activeElement : document.querySelector('.input'); const cs = getComputedStyle(el); return { layers: (cs.backgroundImage.match(/gradient/g) || []).length, pos: cs.backgroundPosition, color: cs.backgroundColor, focused: el === document.activeElement }; })()`
  const before = await win.webContents.executeJavaScript(READ)
  win.webContents.sendInputEvent({ type: 'mouseDown', x: box.x, y: box.y, button: 'left', clickCount: 1 })
  await wait(400)
  const during = await win.webContents.executeJavaScript(READ)
  win.webContents.sendInputEvent({ type: 'mouseUp', x: box.x, y: box.y, button: 'left', clickCount: 1 })
  await wait(400)
  const afterFocus = await win.webContents.executeJavaScript(READ)
  console.log(JSON.stringify({ before, during, afterFocus }, null, 2))
  console.log('[GLASS_KEPT_ON_FOCUS] ' + (afterFocus.layers === 2))
  console.log('[PRESS_SHIFT] ' + (during.pos !== afterFocus.pos))
  app.exit(0)
})